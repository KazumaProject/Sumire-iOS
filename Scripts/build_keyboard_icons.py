#!/usr/bin/env python3
"""Translate pinned Android vector paths into native UIKit drawing instructions."""
import hashlib, pathlib, re, subprocess, xml.etree.ElementTree as ET
ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / '.reference/JapaneseKeyboard'
REVISION = 'df1f38315bf56d860d32919a3eaed6a75499e91e'
ICONS = {'paste':'content_paste_24px', 'left':'baseline_arrow_left_24', 'globe':'language_24dp',
         'delete':'backspace_24px', 'enter':'baseline_keyboard_return_24', 'resize':'keyboard_24px',
         'done':'baseline_check_24', 'mode':'input_mode_english_custom', 'space':'baseline_space_bar_24', 'shift':'shift_24px', 'shiftActive':'shift_fill_24px', 'capsLock':'caps_lock', 'capsLockOutline':'caps_lock_outline', 'right':'baseline_arrow_right_24', 'undo':'undo_24px', 'directOn':'language_japanese_kana_right_24px', 'directOff':'language_japanese_kana_left_24px', 'romajiOn':'language_japanese_kana_left_bold_24px', 'romajiOff':'language_japanese_kana_right_bold_24px'}
A = '{http://schemas.android.com/apk/res/android}'

def translate(data):
    tokens = re.findall(r'[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?', data)
    i=0; command=None; x=y=0; start=(0,0); previous=None; control=None; lines=[]
    def point(p): return f'CGPoint(x: {p[0]:g}, y: {p[1]:g})'
    while i<len(tokens):
        if tokens[i].isalpha(): command=tokens[i];i+=1
        kind=command.upper();relative=command.islower()
        if kind=='Z':
            lines.append('p.closeSubpath()');x,y=start;previous='Z';control=None;command=None;continue
        counts={'M':2,'L':2,'H':1,'V':1,'Q':4,'T':2,'C':6}
        if kind not in counts: raise ValueError('Unsupported vector command '+kind)
        n=counts[kind];values=list(map(float,tokens[i:i+n]));i+=n
        if len(values)!=n: raise ValueError('Truncated vector')
        def xy(offset): return (values[offset]+(x if relative else 0), values[offset+1]+(y if relative else 0))
        end=None
        if kind in ('M','L'):
            end=xy(0);lines.append(f'p.{"move" if kind=="M" else "addLine"}(to: {point(end)})')
            if kind=='M': start=end;command='l' if relative else 'L'
        elif kind in ('H','V'):
            end=(values[0]+(x if relative else 0),y) if kind=='H' else (x,values[0]+(y if relative else 0))
            lines.append(f'p.addLine(to: {point(end)})')
        elif kind in ('Q','T'):
            c=xy(0) if kind=='Q' else (2*x-control[0],2*y-control[1]) if previous in ('Q','T') else (x,y)
            end=xy(2 if kind=='Q' else 0);lines.append(f'p.addQuadCurve(to: {point(end)}, control: {point(c)})');control=c
        elif kind=='C':
            c1,c2,end=xy(0),xy(2),xy(4);lines.append(f'p.addCurve(to: {point(end)}, control1: {point(c1)}, control2: {point(c2)})')
        x,y=end;previous=kind
        if kind not in ('Q','T'): control=None
    return lines

def main():
    if subprocess.check_output(['git','-C',str(SOURCE),'rev-parse','HEAD'],text=True).strip()!=REVISION: raise ValueError('Wrong reference revision')
    files=['core/src/main/res/drawable/'+name+'.xml' for name in ICONS.values()]
    subprocess.run(['git','-C',str(SOURCE),'diff','--exit-code','HEAD','--',*files],check=True)
    lines=['// Generated by Scripts/build_keyboard_icons.py; do not edit paths by hand.',
           '// Source: JapaneseKeyboard '+REVISION+'; see Resources/KeyboardIconsNotice.txt.',
           'import UIKit', '', 'enum KeyboardIcon: CaseIterable {', '    case '+', '.join(ICONS),
           '    private static let images = Dictionary(uniqueKeysWithValues: allCases.map { ($0, $0.render()) })',
           '    var image: UIImage { Self.images[self]! }',
           '    private func render() -> UIImage {',
           '        let renderer = UIGraphicsImageRenderer(size: CGSize(width: 24, height: 24))',
           '        return renderer.image { context in', '            UIColor.black.setFill()', '            UIColor.black.setStroke()', '            switch self {']
    notices=[]
    for key,name in ICONS.items():
        file=SOURCE/'core/src/main/res/drawable'/(name+'.xml');root=ET.parse(file).getroot()
        if any(e.tag not in ('vector','path','group') for e in root.iter()): raise ValueError('Unsupported vector element')
        notices.append(f'{name}.xml SHA-256 {hashlib.sha256(file.read_bytes()).hexdigest()}')
        lines += [f'            case .{key}:',f'                context.cgContext.scaleBy(x: 24 / {root.attrib[A+"viewportWidth"]}.0, y: 24 / {root.attrib[A+"viewportHeight"]}.0)']
        def emit(parent):
            result=[]
            for child in parent:
                if child.tag == 'group':
                    if set(child.attrib) - {A+'translateX', A+'translateY'}:
                        raise ValueError('Unsupported vector group transform')
                    x=float(child.attrib.get(A+'translateX', '0'));y=float(child.attrib.get(A+'translateY', '0'))
                    if not __import__('math').isfinite(x) or not __import__('math').isfinite(y):
                        raise ValueError('Non-finite vector translation')
                    result += ['                context.cgContext.saveGState()',
                               f'                context.cgContext.translateBy(x: {x:g}, y: {y:g})']
                    result += emit(child)
                    result += ['                context.cgContext.restoreGState()']
                elif child.tag == 'path':
                    result += ['                do {','                    let p = CGMutablePath()']
                    result += ['                    '+line for line in translate(child.attrib[A+'pathData'])]
                    fill = child.attrib.get(A+'fillColor', '@android:color/transparent') != '@android:color/transparent'
                    stroke = child.attrib.get(A+'strokeColor', '@android:color/transparent') != '@android:color/transparent'
                    if stroke:
                        width=float(child.attrib.get(A+'strokeWidth', '0'))
                        if not __import__('math').isfinite(width) or width < 0:
                            raise ValueError('Invalid vector stroke width')
                        cap=child.attrib.get(A+'strokeLineCap', 'butt')
                        join=child.attrib.get(A+'strokeLineJoin', 'miter')
                        if cap not in ('butt','round','square') or join not in ('miter','round','bevel'):
                            raise ValueError('Unsupported vector stroke style')
                        result += ['                    context.cgContext.saveGState()',
                                   f'                    context.cgContext.setLineWidth({width:g})',
                                   f'                    context.cgContext.setLineCap(.{cap})',
                                   f'                    context.cgContext.setLineJoin(.{join})']
                    result += ['                    context.cgContext.addPath(p)']
                    if stroke:
                        result += [f'                    context.cgContext.drawPath(using: .{"fillStroke" if fill else "stroke"})',
                                   '                    context.cgContext.restoreGState()']
                    elif fill:
                        operation='fillPath(using: .evenOdd)' if child.attrib.get(A+'fillType') == 'evenOdd' else 'fillPath()'
                        result += [f'                    context.cgContext.{operation}']
                    result += ['                }']
            return result
        lines += emit(root)
    lines += ['            }','        }.withRenderingMode(.alwaysTemplate)','    }','}']
    (ROOT/'Shared/KeyboardIcon.swift').write_text('\n'.join(lines)+'\n')
    dest=ROOT/'Shared/Resources';dest.mkdir(exist_ok=True)
    (dest/'KeyboardIconsNotice.txt').write_text('Vector paths copied from JapaneseKeyboard/core/src/main/res/drawable\nRevision: '+REVISION+'\nConverted to UIKit path commands; original geometry preserved.\n'+'\n'.join(notices)+'\n\n'+(SOURCE/'LICENSE').read_text())
if __name__=='__main__': main()
